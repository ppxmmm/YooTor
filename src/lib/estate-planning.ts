export type WillDetails = {
  name: string;
  date: string;
  place: string;
  dispositions: string;
  executor: string;
};
export function buildWillDraft(details: WillDetails) {
  if (Object.values(details).some((value) => !value.trim()))
    throw new Error('กรุณากรอกข้อมูลพินัยกรรมให้ครบ');
  return `พินัยกรรมแบบธรรมดา — ฉบับร่างเพื่อทบทวน
จัดทำ ณ ${details.place}
วันที่ ${details.date}

ข้าพเจ้า ${details.name} ขอแสดงเจตนาเกี่ยวกับทรัพย์สินของข้าพเจ้าภายหลังถึงแก่ความตาย ดังนี้

${details.dispositions}

ข้าพเจ้าประสงค์ให้ ${details.executor} เป็นผู้จัดการมรดกของข้าพเจ้า

ลงชื่อ ____________________ ผู้ทำพินัยกรรม
ลงชื่อ ____________________ พยานคนที่ 1
ลงชื่อ ____________________ พยานคนที่ 2

คำแนะนำก่อนนำไปใช้: ตรวจสอบทรัพย์สิน ผู้รับ และข้อความทั้งหมดกับผู้เชี่ยวชาญ พินัยกรรมแบบธรรมดาต้องระบุวัน เดือน ปี และผู้ทำลงลายมือชื่อต่อหน้าพยานอย่างน้อยสองคนพร้อมกัน โดยพยานลงลายมือชื่อรับรองในขณะนั้นด้วย ตรวจสอบคุณสมบัติและข้อห้ามของพยานและผู้เขียนก่อนลงนาม การบันทึกหรือดาวน์โหลดจากระบบยังไม่ใช่การลงนามพินัยกรรม`;
}
